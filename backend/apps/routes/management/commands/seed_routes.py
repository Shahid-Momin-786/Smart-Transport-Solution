DEFAULT_DEPOT_CODE = 'SWG'  # fallback


def guess_depot(source, destination):
    """Heuristically assign a depot based on source/destination text."""
    combined = (source + ' ' + destination).lower()
    for (keywords, code) in DEPOT_KEYWORD_MAP:
        if any(kw.lower() in combined for kw in keywords):
            return code
    return DEFAULT_DEPOT_CODE


def parse_fare(distance_km):
    """Calculate PMPL fare based on distance (approximate slab rates)."""
    try:
        d = float(distance_km)
    except (ValueError, TypeError):
        return 10.0
    if d <= 3:
        return 7.0
    elif d <= 5:
        return 10.0
    elif d <= 8:
        return 13.0
    elif d <= 12:
        return 17.0
    elif d <= 18:
        return 22.0
    elif d <= 25:
        return 28.0
    elif d <= 35:
        return 35.0
    else:
        return 42.0


