def parse_source_destination(description):
    """Extract source and destination from route description."""
    description = description.strip()
    separators = [' To ', ' to ']
    for sep in separators:
        if sep in description:
            parts = description.split(sep, 1)
            return parts[0].strip(), parts[1].strip()
    return description, description


class Command(BaseCommand):
    help = 'Seed PMPL Pune real bus routes from OpenCity dataset (clears previous data)'

    def add_arguments(self, parser):
        parser.add_argument(
            '--no-clear',
            action='store_true',
            help='Skip clearing existing routes (add-only mode)',
        )

    def handle(self, *args, **options):
        # ── Build depot lookup ─────────────────────────────────────────────
        depot_map = {d.code: d for d in Depot.objects.all()}
        if not depot_map:
            self.stdout.write(self.style.ERROR(
                'No depots found! Please run seed_depots first: '
                'python manage.py seed_depots'
            ))
            return

        self.stdout.write(self.style.WARNING(
            f'Found {len(depot_map)} depots: {list(depot_map.keys())}'
        ))

        with transaction.atomic():
            # ── Clear existing routes & stops ──────────────────────────────
            if not options.get('no_clear'):
                stop_count = Stop.objects.count()
                route_count = Route.objects.count()
                Stop.objects.all().delete()
                Route.objects.all().delete()
                self.stdout.write(self.style.WARNING(
                    f'Cleared {route_count} routes and {stop_count} stops.'
                ))

            # ── Seed PMPL routes ───────────────────────────────────────────
            created = 0
            skipped = 0
            fallback_depot_used = 0

            for (route_id, description, distance_km) in RAW_PMPL_DATA:
                route_number = route_id.strip()
                source, destination = parse_source_destination(description)

                depot_code = guess_depot(source, destination)
                if depot_code not in depot_map:
                    depot_code = DEFAULT_DEPOT_CODE
                    fallback_depot_used += 1

                depot = depot_map.get(depot_code) or list(depot_map.values())[0]
                fare = parse_fare(distance_km)

                _, was_created = Route.objects.get_or_create(
                    route_number=route_number,
                    defaults={
                        'route_name': description,
                        'source': source,
                        'destination': destination,
                        'distance': distance_km,
                        'fare': fare,
                        'depot': depot,
                        'is_active': True,
                    }
                )

                if was_created:
                    created += 1
                else:
                    skipped += 1

        self.stdout.write(self.style.SUCCESS(
            f'\n[SUCCESS] PMPL Route Seeding Complete!'
            f'\n   Routes created : {created}'
            f'\n   Already existed: {skipped}'
            f'\n   Fallback depot : {fallback_depot_used} routes -> {DEFAULT_DEPOT_CODE}'
            f'\n   Total in DB    : {Route.objects.count()}'
        ))
        self.stdout.write(self.style.SUCCESS(
            '\nData source: OpenCity Pune - PMPL Bus Routes Dataset'
        ))
